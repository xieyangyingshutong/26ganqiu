# Missing-ball state machine:
#   0 .. BALL_SHORT_PREDICT_MS:
#       bridge ordinary detector flicker using constant-velocity prediction.
#   BALL_EDGE_CONFIRM_MS .. BALL_EDGE_RECOVERY_MS:
#       when the last fresh state was near an end and moving outward, infer
#       that the ball entered the outer zone. Move the estimate from +/-100
