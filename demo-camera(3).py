"""
CanMV K230 ball-on-beam vision, three operating modes and UART4 telemetry.

LCD touch modes:
    M1 CENTER : keep the ball at beam center (0 mm).
    M2 SWEEP  : command +50 mm, reverse on arrival, then hold -50 mm.
    M3 TOUCH  : touch any point on the detected beam to choose the target.

UART4:
    GPIO36 -> UART4_TXD
    GPIO37 -> UART4_RXD (initialized, may be left unconnected)
    115200, 8 data bits, no parity, 1 stop bit

The detected beam/track (class 0) defines the physical coordinate system:
its left scale is -120.0 mm, center is 0.0 mm, and right scale is +120.0 mm.

One 12-byte packet is sent for every processed frame. All multi-byte fields
are little-endian:

    Byte 0       : header 0xAA
    Byte 1       : header 0x55
    Byte 2       : frame sequence, uint8
    Byte 3       : flags
                     bit 0: ball position is valid
                     bit 1: setpoint is valid
                     bit 2: track detected in the current frame
                     bit 3: mode 2 sequence is complete
                     bit 4..5: mode number (1, 2 or 3)
                     bit 6: ball detected in the current frame
                     bit 7: edge-loss recovery is active
    Byte 4       : ball confidence, uint8 (0..100 percent)
    Byte 5..6    : ball position, int16 (unit: 0.1 mm)
    Byte 7..8    : ball velocity, int16 (unit: 0.1 mm/s)
    Byte 9..10   : active setpoint, int16 (unit: 0.1 mm)
    Byte 11      : XOR of bytes 0..10
"""

